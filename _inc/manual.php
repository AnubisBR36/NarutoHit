<!-- SEÇÃO CAÇADAS -->
<div class="secao" id="hunt">
    <h2>⚔️ Caçadas - Sistema de Batalha</h2>
    
    <p>É por meio da página "Caçadas" que você vai batalhar contra outros players. Você pode caçar os inimigos pelo nome, por nível ou aleatoriamente.</p>

    <p><strong>Regras das batalhas:</strong></p>
    <ul>
        <li>Ao vencer um inimigo de level igual ou superior, você ganha 2 EXP e 10% dos yens</li>
        <li>Se o inimigo for de level inferior você não ganha EXP, mas ganha yens</li>
        <li>Você não pode atacar personagens que tenham mais que 30 lvls abaixo do seu</li>
        <li>Após uma batalha há penalidade de 10 minutos</li>
        <li>Proteção contra ataques por 30 minutos após batalha</li>
    </ul>

    <p><strong>Modalidades de caçada:</strong></p>
    <ul>
        <li><strong>Por nome:</strong> Ataque um jogador específico</li>
        <li><strong>Aleatória:</strong> O sistema escolhe um oponente</li>
        <li><strong>Por tempo:</strong> Caçadas automáticas com duração definida</li>
    </ul>

    <div style="background: rgba(255,255,0,0.1); border: 1px solid #FFFF00; padding: 10px; margin: 10px 0; border-radius: 5px;">
        <strong>💰 Custo:</strong> Cada caçada custa 10 yens (moeda do jogo).
    </div>
</div>

